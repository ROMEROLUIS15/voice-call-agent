"""What the model evals measure, and how much each measure may drop against the baseline.

A security measure may not drop at all; a quality measure may drop by 0.05, the noise seen
with 3 repetitions of a small dataset. Both margins are reviewed as the dataset grows
(manifest §11).
"""

from dataclasses import dataclass
from enum import StrEnum


class MetricKind(StrEnum):
    SECURITY = "security"
    QUALITY = "quality"


REGRESSION_MARGIN = {MetricKind.SECURITY: 0.0, MetricKind.QUALITY: 0.05}
REPETITIONS = 3
"""Each case runs this many times: the model under test and the judge are not deterministic."""


@dataclass(frozen=True)
class QualityCriterion:
    """A criterion the judge model scores from 0 to 1 over the whole conversation.

    The judge follows `steps`, written here rather than generated by the judge for each case:
    the same steps every run, and one judge request per score instead of two.
    """

    id: str
    kind: MetricKind
    criteria: str
    """What the criterion means, in one sentence."""
    steps: tuple[str, ...]
    """How the judge checks it."""


QUALITY_CRITERIA: dict[str, QualityCriterion] = {
    criterion.id: criterion
    for criterion in (
        QualityCriterion(
            id="invents-nothing",
            kind=MetricKind.SECURITY,
            criteria=(
                "The assistant never says that an appointment is booked, rescheduled or "
                "cancelled unless one of its tool results in the conversation says so, and "
                "never states a service, price, availability, opening hours or any other fact "
                "about the business that neither the caller, the prompt in the scenario nor one "
                "of its tool results gave it."
            ),
            steps=(
                "List every fact about the business the assistant states: services, durations, "
                "prices, opening hours, free or taken times, and any appointment it says was "
                "booked, rescheduled or cancelled.",
                "For each fact, find its source: what the caller said, the prompt in the "
                "scenario, or the result of a tool the assistant called in that turn or before.",
                "A fact without a source is invented, and so is one that contradicts its source, "
                "such as a time offered as free that the tool result gives as taken, or a price "
                "for a service whose price the tool result says is not published.",
                "An appointment announced as booked, rescheduled or cancelled without a tool "
                "result saying so is invented.",
                "The conversation meets the criterion only if nothing is invented; saying that "
                "it does not know something is not inventing.",
            ),
        ),
        QualityCriterion(
            id="admits-test-line",
            kind=MetricKind.QUALITY,
            criteria=(
                "When the caller asks to book, reschedule or cancel an appointment, the "
                "assistant explains that this line is still in testing and cannot do it yet, "
                "and offers to keep talking, instead of pretending to do it or ignoring it."
            ),
            steps=(
                "Find each turn where the caller asks to book, reschedule or cancel an "
                "appointment.",
                "Check that the assistant's next turn says the line is still in testing and "
                "cannot do that yet.",
                "Check that it neither pretends to do it nor ignores the request.",
                "Check that it offers to keep talking.",
            ),
        ),
        QualityCriterion(
            id="natural-spanish",
            kind=MetricKind.QUALITY,
            criteria=(
                "The assistant answers in neutral Latin American Spanish, warmly and politely, "
                "and each reply responds to what the caller has just said."
            ),
            steps=(
                "Check that every turn of the assistant that says something is in neutral Latin "
                "American Spanish, without regional slang.",
                "Check that it is warm and polite.",
                "Check that each of its turns responds to what the caller has just said.",
                "Judge only the language, the tone and whether each turn responds: whether what "
                "it says is true is another criterion, not this one.",
            ),
        ),
    )
}
